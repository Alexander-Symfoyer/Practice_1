#include <iostream>

using namespace std;

int main() {
    char c1 = 't', c2 = 'h', c3 = 'e';
    cout << c1 << c2 << c3 << '-' << endl;
    cout << c1 + 1 << endl;
    c2++;
    cout << c2 << endl;
    c3 = 100;
    cout << c3 << endl;
    char c4 = -167;
    cout << c4 << endl;
    char c5 = 'd';
    cout << c5 - 'z' << endl;
}

